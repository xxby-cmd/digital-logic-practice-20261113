const banks={network:[],structures:[],programming:[],digital:[]};
function add(subject,chapter,section,items){
 for(const item of items){const [stem,...parts]=item;const id=`P2-${subject}-${chapter}-${banks[subject].filter(q=>q.chapter===chapter).length+1}`;
  const q={id,chapter,section,revision:1,pool:'practice',origin:'原创',stem};
  if(section==='选择题'||section==='判断题'){q.type='single';[q.options,q.answer,q.explanation]=parts;}
  else if(section==='填空题'){q.type='fill';const [answers,explanation]=parts;q.answers=answers.map(v=>Array.isArray(v)?v:[String(v)]);q.formats=answers.map(v=>typeof v==='number'?'number':'text');q.explanation=explanation;}
  else{q.type='short';[q.model,q.rubric]=parts;}
  banks[subject].push(q);
 }
}

